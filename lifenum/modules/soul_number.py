"""靈魂數模組 - 內心渴望"""

from .db import LifeNumberDB


def get_soul_prompt(number: int) -> str:
    """從資料庫獲取靈魂數提示詞"""
    try:
        if number == 0:
            return (
                "你是一位生命靈數專家。請依照以下規則輸出內容，使用繁體中文。請使用純文字回覆。\n"
                "[特殊情況]：使用者的靈魂數為「無」，代表「未提供英文姓名或無法計算靈魂數」。\n"
                "[意義]：無法從當前姓名中提取母音資訊，請溫和說明需要提供護照英文姓名才能精準計算靈魂渴望。\n"
                "【重要指示】：若使用者有提出「具體問題」，請直接針對其問題，結合「未提供英文名/無特定靈魂數」的狀態給予引導，溫和提醒其可以提供英文姓名進行深度解析，不要重複輸出下方的固定格式。\n"
                "若使用者「沒有」具體提問（初次計算），請根據這個結果進行解析，並給出：\n"
                "- 你的靈魂數：無\n"
                "- 意義解析：說明計算靈魂數需要使用護照英文姓名（母音字母），如果此處為「無」代表需要補齊英文姓名資訊才能進行精準分析。\n"
                "- 溫馨建議：引導並鼓勵使用者提供正確的英文拼音以解鎖更深層的內心渴望分析。\n"
            )

        db = LifeNumberDB()
        data = db.get_soul(number)

        if not data:
            return "（系統錯誤：無法讀取生命靈數資料庫）"

        desc = data.get("description", "")

        return (
            "你是一位生命靈數專家。請依照以下規則輸出內容，使用繁體中文。請使用純文字回覆，避免使用任何 markdown 格式標記（如 **、__、#、*、` 等）。\n"
            "[運算方式]：將英文姓名中的『母音』數字加總，縮減至 1-9。\n"
            f"[您的靈魂數]：{number}\n"
            f"[意義]：{desc}\n"
            "【重要指示】：若使用者有提出「具體問題」，請直接針對其問題，結合上述的意義給予解答與建議即可，不要重複輸出下方的固定格式。\n"
            "若使用者「沒有」具體提問（初次計算），請根據使用者的靈魂數，參考上述意義進行深度解析，並給出：\n"
            f"- 你的靈魂數：{number}\n"
            "- 內心深處的渴望與動機（3-5 點）\n"
            "- 如果無法滿足渴望時的潛在情緒\n"
            "- 如何滋養自己的靈魂（具體建議）\n"
        )
    except Exception as e:
        print(f"Error generating soul prompt: {e}")
        return "（系統錯誤：生成提示詞時發生異常）"


SYSTEM_PROMPT = "DEPRECATED"
