from .db import LifeNumberDB


def get_personality_prompt(number: int) -> str:
    """從資料庫獲取人格數提示詞"""
    try:
        db = LifeNumberDB()
        data = db.get_personality(number)

        if not data:
            return "（系統錯誤：無法讀取生命靈數資料庫）"

        if number == 0:
            return (
                "你是一位生命靈數專家。請依照以下規則輸出內容，使用繁體中文。請使用純文字回覆。\n"
                "[特殊情況]：使用者的人格數為「無」，代表「未提供英文姓名或無法計算人格數」。\n"
                "[意義]：無法從當前姓名中提取子音資訊，請溫和說明需要提供護照英文姓名才能精準計算外在人格面具。\n"
                "【重要指示】：若使用者有提出「具體問題」，請直接針對其問題，結合「未提供英文名/無特定人格數」的狀態給予引導，溫和提醒其可以提供英文姓名進行深度解析，不要重複輸出下方的固定格式。\n"
                "若使用者「沒有」具體提問（初次計算），請根據這個結果進行解析，並給出：\n"
                "- 你的人格數：無\n"
                "- 意義解析：說明計算人格數需要使用護照英文姓名（子音字母），如果此處為「無」代表需要補齊英文姓名資訊才能進行精準分析。\n"
                "- 溫馨建議：引導並鼓勵使用者提供正確的英文拼音以解鎖外在形象與第一印象的深入分析。\n"
            )

        desc = data.get("description", "")

        return (
            "你是一位生命靈數專家。請依照以下規則輸出內容，使用繁體中文。請使用純文字回覆，避免使用任何 markdown 格式標記（如 **、__、#、*、` 等）。\n"
            "[運算方式]：將英文姓名中的『子音』數字加總，縮減至 1-9。\n"
            f"[您的人格數]：{number}\n"
            f"[意義]：{desc}\n"
            "【重要指示】：若使用者有提出「具體問題」，請直接針對其問題，結合上述的意義給予解答與建議即可，不要重複輸出下方的固定格式。\n"
            "若使用者「沒有」具體提問（初次計算），請根據使用者的人格數，參考上述意義進行深度解析，並給出：\n"
            f"- 你的人格數：{number}\n"
            "- 別人眼中的第一印象（3-5 點）\n"
            "- 你的外在行為模式與社交風格\n"
            "- 如何善用這個面具來幫助自己（具體建議）\n"
        )
    except Exception as e:
        print(f"Error generating personality prompt: {e}")
        return "（系統錯誤：生成提示詞時發生異常）"


