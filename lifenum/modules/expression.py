"""表達數模組 - 整體表達風格與社交風格"""

from .db import LifeNumberDB


def get_expression_prompt(number: int) -> str:
    """從資料庫獲取表達數提示詞"""
    try:
        db = LifeNumberDB()
        data = db.get_expression(number)

        if not data:
            return "（系統錯誤：無法讀取生命靈數資料庫）"

        if number == 0:
            return (
                "你是一位生命靈數專家。請依照以下規則輸出內容，使用繁體中文。請使用純文字回覆。\n"
                "[特殊情況]：使用者的表達數為「無」，代表「未提供英文姓名或無法計算表達數」。\n"
                "[意義]：無法從當前姓名中提取字母資訊，請溫和說明需要提供護照英文姓名才能精準計算您的表達與天賦才華。\n"
                "【重要指示】：若使用者有提出「具體問題」，請直接針對其問題，結合「未提供英文名/無特定表達數」的狀態給予引導，溫和提醒其可以提供英文姓名進行深度解析，不要重複輸出下方的固定格式。\n"
                "若使用者「沒有」具體提問（初次計算），請根據這個結果進行解析，並給出：\n"
                "- 你的表達數：無\n"
                "- 意義解析：說明計算表達數需要使用護照英文姓名（全部字母），如果此處為「無」代表需要補齊英文姓名資訊才能進行精準分析。\n"
                "- 溫馨建議：引導並鼓勵使用者提供正確的英文拼音以解鎖整體天賦才能與處事風格的深入分析。\n"
            )

        title = data.get("title", "")
        desc = data.get("description", "")

        return (
            "你是一位生命靈數專家。請依照以下規則輸出內容，使用繁體中文。請使用純文字回覆，避免使用任何 markdown 格式標記（如 **、__、#、*、` 等）。\n"
            "[運算方式]：將英文姓名中的『所有字母』數字加總，縮減至 1-9。\n"
            f"[您的表達數]：{number} ｜ {title}\n"
            f"[意義]：{desc}\n"
            "【重要指示】：若使用者有提出「具體問題」，請直接針對其問題，結合上述的意義給予解答與建議即可，不要重複輸出下方的固定格式。\n"
            "若使用者「沒有」具體提問（初次計算），請根據使用者的表達數，參考上述意義進行深度解析，並給出：\n"
            f"- 你的表達數：{number}\n"
            "- 你的處事風格與能力（3-5 點）\n"
            "- 適合發揮的舞台或工作類型\n"
            "- 如何將此能力運用在生活中（具體建議）\n"
        )
    except Exception as e:
        print(f"Error generating expression prompt: {e}")
        return "（系統錯誤：生成提示詞時發生異常）"


SYSTEM_PROMPT = "DEPRECATED"
